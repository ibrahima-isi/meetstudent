-- Refresh-token reuse detection: every secret a session rotates away is remembered (SHA-256 only, like
-- refresh_tokens.token) for the 7-day inactivity window. Presenting one again means the token was copied, and the
-- whole session is ended (a short grace applies to the latest one only, for concurrent refreshes). The rows go with
-- their session. Existing sessions start with an empty history: nobody is signed out by the deployment.
CREATE TABLE refresh_token_history (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    refresh_token_id integer NOT NULL REFERENCES refresh_tokens(id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL,
    rotated_at timestamp with time zone NOT NULL,
    CONSTRAINT refresh_token_history_token_hash_key UNIQUE (token_hash)
);
CREATE INDEX refresh_token_history_refresh_token_id_idx ON refresh_token_history (refresh_token_id);
CREATE INDEX refresh_token_history_rotated_at_idx ON refresh_token_history (rotated_at);
