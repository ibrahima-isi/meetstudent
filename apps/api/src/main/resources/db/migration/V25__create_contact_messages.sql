-- Messages sent through the public contact form (POST /api/v1/contact). Kept so the back office can
-- read them later; the sender is anonymous, so there is no user reference and no IP address is stored.
CREATE TABLE contact_messages (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sender_email varchar(254) NOT NULL,
    subject varchar(150) NOT NULL,
    body varchar(5000) NOT NULL,
    -- 'fr' or 'en' when the form sent it; null otherwise.
    language varchar(2),
    created_at timestamp with time zone NOT NULL
);

CREATE INDEX idx_contact_messages_created_at ON contact_messages (created_at);
