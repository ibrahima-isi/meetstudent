-- Optional email verification (and, later, password reset) with hashed single-use tokens.
-- Every account that exists today is treated as verified; new registrations start unverified.
ALTER TABLE users ADD COLUMN email_verified boolean NOT NULL DEFAULT false;
UPDATE users SET email_verified = true;

CREATE TABLE user_tokens (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- SET NULL, not CASCADE: the row is evidence for the per-address mail cap and must outlive the account.
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    purpose varchar(32) NOT NULL,
    token_hash varchar(64) NOT NULL,
    email varchar(255) NOT NULL,
    issued_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    consumed_at timestamp with time zone,
    created_at timestamp(6) without time zone,
    created_by integer,
    modified_at timestamp(6) without time zone,
    modified_by integer,
    CONSTRAINT uq_user_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX idx_user_tokens_user_purpose_issued ON user_tokens (user_id, purpose, issued_at);
