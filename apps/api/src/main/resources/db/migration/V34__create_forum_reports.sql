-- Forum reports: a user flags one message (a thread's opening message or a reply) for the administrators.
-- Exactly one target, one report per reporter and message, reason <= 255, status OPEN/HANDLED/DISMISSED.
-- A report goes with its message (ON DELETE CASCADE: deleting a reply, or a thread and so its replies, removes the
-- reports). It outlives its reporter's account: reporter_id becomes NULL (the report is kept, anonymous; several
-- anonymous reports on one message coexist because NULLs are distinct in a unique constraint).
-- Reports are personal data: only the admin endpoints read them.
CREATE TABLE forum_reports (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    thread_id integer REFERENCES forum_threads(id) ON DELETE CASCADE,
    reply_id integer REFERENCES forum_replies(id) ON DELETE CASCADE,
    reporter_id integer REFERENCES users(id) ON DELETE SET NULL,
    reason varchar(255) NOT NULL,
    -- The start of the reported text as it was when the report was made (<= 1000 characters), so that an edit made
    -- afterwards is visible to the administrator.
    target_snapshot varchar(1000) NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'OPEN',
    created_at timestamp with time zone NOT NULL,
    handled_at timestamp with time zone,
    -- The administrator who closed the report (NULL while open, or once that account is deleted).
    handled_by integer REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_forum_reports_one_target CHECK ((thread_id IS NULL) <> (reply_id IS NULL)),
    CONSTRAINT chk_forum_reports_status CHECK (status IN ('OPEN', 'HANDLED', 'DISMISSED')),
    CONSTRAINT uq_forum_reports_reporter_thread UNIQUE (reporter_id, thread_id),
    CONSTRAINT uq_forum_reports_reporter_reply UNIQUE (reporter_id, reply_id)
);

-- Serves the queue: filtered by status, newest first.
CREATE INDEX idx_forum_reports_status_created ON forum_reports (status, created_at DESC, id DESC);
-- The cascade from a deleted thread or reply looks reports up by target.
CREATE INDEX idx_forum_reports_thread ON forum_reports (thread_id);
CREATE INDEX idx_forum_reports_reply ON forum_reports (reply_id);
