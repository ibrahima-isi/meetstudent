-- Forum: threads and their replies (plain text only, no nesting).
-- An author who deletes his account leaves the messages in place: author_id becomes NULL and the API
-- reports authorDeleted. A deleted school only detaches the threads that mentioned it.
-- "hidden" is set by moderation (a later ticket); hidden messages are never returned to non-admins.
CREATE TABLE forum_threads (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title varchar(150) NOT NULL,
    body varchar(5000) NOT NULL,
    author_id integer REFERENCES users(id) ON DELETE SET NULL,
    school_id integer REFERENCES schools(id) ON DELETE SET NULL,
    locked boolean NOT NULL DEFAULT false,
    hidden boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL,
    modified_at timestamp with time zone
);

CREATE INDEX idx_forum_threads_created_at ON forum_threads (created_at DESC, id DESC);
-- Serves the school filter in its newest-first order.
CREATE INDEX idx_forum_threads_school ON forum_threads (school_id, created_at DESC, id DESC);
CREATE INDEX idx_forum_threads_author ON forum_threads (author_id);

CREATE TABLE forum_replies (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    thread_id integer NOT NULL REFERENCES forum_threads(id) ON DELETE CASCADE,
    body varchar(5000) NOT NULL,
    author_id integer REFERENCES users(id) ON DELETE SET NULL,
    hidden boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL,
    modified_at timestamp with time zone
);

CREATE INDEX idx_forum_replies_thread_created ON forum_replies (thread_id, created_at DESC, id DESC);
CREATE INDEX idx_forum_replies_author ON forum_replies (author_id);
